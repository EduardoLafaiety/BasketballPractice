import { expect, test } from '@playwright/test'
import { autorizacao, entrarCom, idDoExercicio, novaConta } from './ajuda'

test('menu móvel mantém foco, fecha por Escape e permite pular ao conteúdo', async ({ page, request }) => {
  const { token } = await novaConta(request)
  await page.setViewportSize({ width: 390, height: 844 })
  await entrarCom(page, token)
  await page.goto('/treinos')
  await expect(page.getByRole('heading', { name: 'Treinos', exact: true })).toBeVisible()
  await page.keyboard.press('Tab')
  await expect(page.getByRole('link', { name: 'Pular para o conteúdo' })).toBeFocused()
  await page.keyboard.press('Enter')
  await expect(page.getByRole('main')).toBeFocused()
  const abrir = page.getByRole('button', { name: 'Mais seções' })
  await abrir.click()
  const menu = page.getByRole('dialog', { name: 'Menu principal' })
  await expect(menu).toBeVisible()
  await menu.getByRole('button', { name: 'Fechar navegação' }).focus()
  await page.keyboard.press('Shift+Tab')
  await expect(menu.getByRole('button', { name: 'Sair' })).toBeFocused()
  await page.keyboard.press('Tab')
  await expect(menu.getByRole('button', { name: 'Fechar navegação' })).toBeFocused()
  await page.keyboard.press('Escape')
  await expect(menu).toHaveCount(0)
  await expect(abrir).toBeFocused()
})

test('move exercício sem arrastar e inicia a rotina confirmada com a duração preservada', async ({ page, request }) => {
  const { token } = await novaConta(request)
  const exerciseId = await idDoExercicio(request, token, 'Lance livre')
  const hoje = await page.evaluate(() => new Date().getDay())
  const origem = (hoje + 1) % 7
  await request.put('/api/routine', { headers: autorizacao(token), data: { days: Array.from({ length: 7 }, (_, day) => ({ day, exercises: day === origem ? [{ exerciseId, minutes: 7 }] : [] })) } })
  await page.setViewportSize({ width: 390, height: 844 })
  await entrarCom(page, token)
  await page.goto('/treinos')
  await page.getByRole('link', { name: 'Montar minha rotina' }).click()
  const mover = page.getByRole('combobox', { name: /^Mover Lance livre/ })
  await mover.selectOption(String(hoje))
  const iniciar = page.getByRole('button', { name: 'Iniciar treino de hoje', exact: true })
  await expect(iniciar).toBeEnabled()
  const remover = page.getByRole('button', { name: 'Remover Lance livre' })
  const caixa = await remover.boundingBox()
  expect(caixa!.width).toBeGreaterThanOrEqual(44)
  expect(caixa!.height).toBeGreaterThanOrEqual(44)
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await iniciar.click()
  await expect(page.getByRole('button', { name: 'Começar', exact: true })).toBeVisible()
  await expect(page.getByText(/1 exercícios · 7 min/)).toBeVisible()
  const treinos = await (await request.get('/api/workouts', { headers: autorizacao(token) })).json()
  const salvo = treinos.find((w: { description: string }) => w.description === `bp-rotina:${hoje}`)
  const detalhe = await (await request.get(`/api/workouts/${salvo.id}`, { headers: autorizacao(token) })).json()
  expect(detalhe.exercises).toMatchObject([{ exerciseId, targetSeconds: 420 }])
})

test('erro no formulário fica associado ao campo e permite correção sem perder o contexto', async ({ page, request }) => {
  const { token } = await novaConta(request)
  const criado = await request.post('/api/exercises', { headers: autorizacao(token), data: { name: 'Exercício de teste', category: 'drible', metric: 'tempo' } })
  const { id } = await criado.json()
  await entrarCom(page, token)
  await page.goto(`/treinos/${id}`)
  await page.getByRole('button', { name: /Editar/ }).click()
  await page.getByRole('textbox', { name: 'Nome', exact: true }).fill('A')
  await page.getByRole('button', { name: 'Salvar', exact: true }).click()
  const nome = page.getByRole('textbox', { name: 'Nome', exact: true })
  await expect(nome).toHaveAttribute('aria-invalid', 'true')
  await expect(nome).toHaveAccessibleDescription('O nome precisa ter pelo menos 2 letras.')
  await expect(nome).toBeFocused()
  await nome.fill('Exercício corrigido')
  await page.getByRole('button', { name: 'Salvar', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Exercício corrigido' }).first()).toBeVisible()
})
