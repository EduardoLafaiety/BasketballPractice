export async function migrate(db: Database) {
  await db.transaction(async (tx) => {
    await tx.query('SET LOCAL statement_timeout = 0')
    // Impede que duas instâncias da API migrem ao mesmo tempo.
    await tx.query('SELECT pg_advisory_xact_lock(4242)')
    await tx.query(`CREATE TABLE IF NOT EXISTS schema_migrations (
      version    integer PRIMARY KEY,
      applied_at timestamptz NOT NULL DEFAULT now()
    )`)
    const { rows } = await tx.query<{ current: number }>(
      'SELECT COALESCE(MAX(version), 0) AS current FROM schema_migrations',
    )

    for (let version = rows[0].current; version < migrations.length; version++) {
      await tx.query(migrations[version])
      await tx.query('INSERT INTO schema_migrations (version) VALUES ($1)', [version + 1])
    }
  })
}
